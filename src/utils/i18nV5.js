// Replaces {placeholders} in a translated string: formatMessage('Hi {name}', { name: 'Phuc' })
export const formatMessage = (template, vars = {}) => String(template || '')
  .replace(/\{(\w+)\}/g, (match, key) => (vars[key] !== undefined ? String(vars[key]) : match))

export const LOCALE_BY_LANG = { vi: 'vi-VN', en: 'en-US', ja: 'ja-JP', ko: 'ko-KR' }

export const formatWeekdayShort = (ts, lang = 'vi') => {
  try {
    return new Date(ts).toLocaleDateString(LOCALE_BY_LANG[lang] || 'en-US', { weekday: 'short' })
  } catch (e) {
    // Older engines without Intl locale data — fall back to an empty label
    return ''
  }
}

export const formatDateTime = (ts, lang = 'vi') => {
  if (!ts) return ''
  try {
    return new Date(ts).toLocaleString(LOCALE_BY_LANG[lang] || 'en-US', { dateStyle: 'medium', timeStyle: 'short' })
  } catch (e) {
    // Intl not available — degrade to ISO string
    return new Date(ts).toISOString()
  }
}
